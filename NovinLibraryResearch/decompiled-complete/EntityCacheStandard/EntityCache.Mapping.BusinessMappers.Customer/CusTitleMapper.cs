namespace EntityCache.Mapping.BusinessMappers.Customer;

public class CusTitleMapper : IItemAsyncMapper<CusTitleBusiness, WebCusTitle>, IItemAsyncMapper<CusTitleBusiness, CusTitleBusiness>, IItemAsyncMapper<WebCusTitle, CusTitleBusiness>
{
	public static CusTitleMapper Instance { get; private set; } = new CusTitleMapper();


	public Task<WebCusTitle> MapAsync(string contextGuid, CusTitleBusiness source, WebCusTitle destination = null, string tranName = "", CancellationToken token = default(CancellationToken))
	{
		try
		{
			if (source == null)
			{
				destination = null;
				return Task.FromResult(destination);
			}
			if (destination == null)
			{
				destination = new WebCusTitle();
			}
			destination.Guid = source.Guid;
			destination.Modified = source.Modified;
			destination.Name = source.Name;
			destination.Status = source.Status;
			destination.ServerStatus = source.ServerStatus;
			destination.DeliveryId = source.DeliveryId;
			destination.DeliveryMessage = source.DeliveryMessage;
			destination.DeliveryShortMessage = source.DeliveryShortMessage;
			destination.HostRefrenced = source.HostRefrenced;
			destination.DeliveryDate = source.DeliveryDate;
		}
		catch (Exception ex)
		{
			WebErrorLog.Instance.StartLog(ex, "", "MapAsync", "D:\\Projects\\NPACC\\WebService_Team\\WebService\\SharedEntityCache\\Mapping\\BusinessMappers\\Customer\\CusTitleMapper.cs", 40);
			throw;
		}
		return Task.FromResult(destination);
	}

	public Task<List<WebCusTitle>> MapListAsync(string contextGuid, IEnumerable<CusTitleBusiness> source, List<WebCusTitle> destination = null, string tranName = "", CancellationToken token = default(CancellationToken))
	{
