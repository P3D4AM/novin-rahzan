	protected OptLookup(StringToken[] stringTokens, int[] tokenIds, int defaultToken)
	{
		lookup = new Dictionary<StringToken, int>(stringTokens.Length);
		for (int i = 0; i < stringTokens.Length; i++)
		{
			lookup.Add(stringTokens[i], tokenIds[i]);
		}
		this.defaultToken = defaultToken;
	}

	public bool TryGetTokenId(StringToken stringToken, ref int tokenId)
	{
		int value;
		bool flag = lookup.TryGetValue(stringToken, out value);
		if (flag)
		{
			tokenId = value;
		}
		else if (defaultToken != -1)
		{
			tokenId = defaultToken;
			flag = true;
		}
		return flag;
	}
