namespace Microsoft.SqlServer.Management.SqlParser.Metadata;

internal static class TypeInfoDispatcher
{
	public static T DispatchVisitor<T>(MetadataTypeInfo typeInfo, IMetadataTypeInfoVisitor<T> visitor, IMetadataObject obj)
	{
		return typeInfo.Id switch
		{
			15 => visitor.Visit((IApplicationRole)obj), 
			16 => visitor.Visit((IAsymmetricKey)obj), 
			18 => visitor.Visit((ICertificate)obj), 
			19 => visitor.Visit((ICheckConstraint)obj), 
			20 => visitor.Visit((IClrDataType)obj), 
			21 => visitor.Visit((ICollation)obj), 
			22 => visitor.Visit((IColumn)obj), 
			24 => visitor.Visit((ICredential)obj), 
			25 => visitor.Visit((ICursorDataType)obj), 
			26 => visitor.Visit((ICursorParameter)obj), 
			27 => visitor.Visit((ICursorVariable)obj), 
			29 => visitor.Visit((IDatabase)obj), 
			30 => visitor.Visit((IDatabaseDdlTrigger)obj), 
			33 => visitor.Visit((IDatabasePermission)obj), 
			35 => visitor.Visit((IDatabaseRole)obj), 
			37 => visitor.Visit((IDefaultConstraint)obj), 
			38 => visitor.Visit((IDmlTrigger)obj), 
			39 => visitor.Visit((IExecutionContext)obj), 
			40 => visitor.Visit((IExtendedStoredProcedure)obj), 
			41 => visitor.Visit((IFileGroup)obj), 
			42 => visitor.Visit((IForeignKeyColumn)obj), 
			43 => visitor.Visit((IForeignKeyConstraint)obj), 
			47 => visitor.Visit((IIndexedColumn)obj), 
			49 => visitor.Visit((ILogin)obj), 
			88 => visitor.Visit((IPartitionScheme)obj), 
			90 => visitor.Visit((IPrimaryKeyConstraint)obj), 
			91 => visitor.Visit((IRelationalIndex)obj), 
			93 => visitor.Visit((IScalarDataType)obj), 
			95 => visitor.Visit((IScalarParameter)obj), 
			96 => visitor.Visit((IScalarValuedFunction)obj), 
			97 => visitor.Visit((IScalarVariable)obj), 
			98 => visitor.Visit((ISchema)obj), 
			100 => visitor.Visit((IServer)obj), 
			101 => visitor.Visit((IServerDdlTrigger)obj), 
			103 => visitor.Visit((ISpatialIndex)obj), 
			104 => visitor.Visit((IStatistics)obj), 
			105 => visitor.Visit((IStoredProcedure)obj), 
			106 => visitor.Visit((ISynonym)obj), 
			107 => visitor.Visit((ISystemClrDataType)obj), 
			108 => visitor.Visit((ISystemDataType)obj), 
			109 => visitor.Visit((ITable)obj), 
			110 => visitor.Visit((ITableDataType)obj), 
			111 => visitor.Visit((ITableParameter)obj), 
			112 => visitor.Visit((ITableValuedFunction)obj), 
			113 => visitor.Visit((ITableVariable)obj), 
			118 => visitor.Visit((IUdtDataMember)obj), 
			120 => visitor.Visit((IUdtMethod)obj), 
			121 => visitor.Visit((IUniqueConstraint)obj), 
			123 => visitor.Visit((IUser)obj), 
			124 => visitor.Visit((IUserDefinedAggregate)obj), 
			125 => visitor.Visit((IUserDefinedClrType)obj), 
			126 => visitor.Visit((IUserDefinedDataType)obj), 
			129 => visitor.Visit((IUserDefinedTableType)obj), 
			131 => visitor.Visit((IView)obj), 
			132 => visitor.Visit((IVoidDataType)obj), 
			133 => visitor.Visit((IXmlDataType)obj), 
			136 => visitor.Visit((IXmlIndex)obj), 
			_ => default(T), 
		};
	}
}
