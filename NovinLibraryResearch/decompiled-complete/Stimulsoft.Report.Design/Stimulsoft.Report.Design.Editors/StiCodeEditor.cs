	public static string GetTextFromDictionaryTree(StiDictionaryControl dictionaryControl, StiReport report, bool isDataExpression = false)
	{
		if (((TreeView)dictionaryControl.tvData).SelectedNode == null)
		{
			return "";
		}
		if (((TreeView)dictionaryControl.tvData).SelectedNode.Tag is StiVariable variable)
		{
			string expressionString = StiVariable.GetExpressionString(variable);
			if (isDataExpression)
			{
				return Funcs.ToExpression(expressionString);
			}
			return expressionString;
		}
