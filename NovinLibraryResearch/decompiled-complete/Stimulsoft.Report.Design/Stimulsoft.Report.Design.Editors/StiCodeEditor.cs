	private bool FindMember(string name, IListMembers members, out int idx)
	{
		name = name.ToLower(CultureInfo.InvariantCulture);
		idx = -1;
		if (name == string.Empty)
		{
			return false;
		}
		for (int i = 0; i < members.Count; i++)
		{
			string str = members[i].Name.ToLowerInvariant();
			if (!str.StartsWithInvariant(name))
			{
				continue;
			}
			bool flag = false;
			idx = i;
			for (int j = i + 1; j < members.Count; j++)
			{
				str = members[j].Name.ToLowerInvariant();
				if (str.StartsWithInvariant(name))
				{
					flag = true;
					if (string.CompareOrdinal(str, name) == 0)
					{
						idx = j;
					}
					break;
				}
			}
			return !flag;
		}
		return false;
	}

