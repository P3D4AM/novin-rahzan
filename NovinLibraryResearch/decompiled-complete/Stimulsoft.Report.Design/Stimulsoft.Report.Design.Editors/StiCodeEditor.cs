		}
	}

	private Atom GetAtom(Atom root, ArrayList words)
	{
		if (words.Count == 0)
		{
			return root;
		}
		string text = words[0] as string;
		foreach (Atom atom in root.Atoms)
		{
			if (atom.Name == text)
			{
				words.RemoveAt(0);
				return GetAtom(atom, words);
			}
		}
		if (words.Count > 1 && (string)words[0] == "this")
		{
			words.RemoveAt(0);
			return GetAtom(root, words);
		}
		return root;
	}

