	public void Init(StiReport report, StiCodeEditorMode codeEditorMode)
	{
		//IL_02f0: Unknown result type (might be due to invalid IL or missing references)
		//IL_02fa: Expected O, but got Unknown
		this.codeEditorMode = codeEditorMode;
		this.report = report;
		DictionaryControl.IsDataExpression = IsDataExpression;
		try
		{
			textSource1.LineTerminator = "\n";
			StiLanguage stiLanguage = report?.Language;
			if ((codeEditorMode & StiCodeEditorMode.SQL) > (StiCodeEditorMode)0)
			{
				if (AllowSQLFormatting)
				{
					Editor.Lexer = new SqlParser();
				}
				biAllowSQLFormatting.Visible = true;
			}
			else
			{
				biAllowSQLFormatting.Visible = false;
				if (stiLanguage != null)
				{
					if (stiLanguage is StiCSharpLanguage)
					{
						if ((codeEditorMode & StiCodeEditorMode.Expression) > (StiCodeEditorMode)0)
						{
							Editor.Lexer = new StiBraceCsParser();
						}
						else
						{
							Editor.Lexer = new CsParser();
						}
					}
					else if (stiLanguage is StiVBLanguage)
					{
						if ((codeEditorMode & StiCodeEditorMode.Expression) > (StiCodeEditorMode)0)
						{
							Editor.Lexer = new StiBraceVbParser();
						}
						else
						{
							Editor.Lexer = new VbParser();
						}
					}
				}
			}
			if (Editor.Lexer is SyntaxParser syntaxParser)
			{
				syntaxParser.Options = SyntaxOptions.Outline | SyntaxOptions.SmartIndent;
				if ((codeEditorMode & StiCodeEditorMode.Expression) > (StiCodeEditorMode)0 || (codeEditorMode & StiCodeEditorMode.ReportCode) > (StiCodeEditorMode)0)
				{
					syntaxParser.Options |= SyntaxOptions.CodeCompletion;
				}
				syntaxParser.Options |= SyntaxOptions.CodeCompletion;
			}
			if ((codeEditorMode & StiCodeEditorMode.WantTabs) > (StiCodeEditorMode)0)
			{
				Editor.AcceptTabs = true;
			}
			else
			{
				Editor.AcceptTabs = false;
			}
			if ((codeEditorMode & StiCodeEditorMode.WantReturns) > (StiCodeEditorMode)0)
			{
				Editor.AcceptReturns = true;
			}
			else
			{
				Editor.AcceptReturns = false;
			}
			Editor.CodeCompletionBox.AutoSize = false;
			Editor.CodeCompletionBox.DropDownCount = 20;
			Editor.CodeCompletionBox.Width = StiScaleUI.I(300);
			Editor.CodeCompletionBox.Height = StiScaleUI.I(300);
			if (((codeEditorMode & StiCodeEditorMode.ReportCode) <= (StiCodeEditorMode)0 && (codeEditorMode & StiCodeEditorMode.Expression) > (StiCodeEditorMode)0) || (codeEditorMode & StiCodeEditorMode.EditorCode) > (StiCodeEditorMode)0)
			{
				Editor.NeedCodeCompletion += Editor_NeedCodeCompletion;
			}
			if ((codeEditorMode & StiCodeEditorMode.ShowDictionary) > (StiCodeEditorMode)0 && report != null)
			{
				try
				{
					((Control)splitter).Visible = (codeEditorMode & StiCodeEditorMode.ShowDictionary) > (StiCodeEditorMode)0;
					((Control)DictionaryControl).Visible = (codeEditorMode & StiCodeEditorMode.ShowDictionary) > (StiCodeEditorMode)0;
					DictionaryControl.NodesMemory = NodesMemoryForEditor;
					((TreeView)DictionaryControl.tvData).BorderStyle = (BorderStyle)1;
					if (StiOptions.Designer.AllowUseDragDrop)
					{
						((Control)DictionaryControl.tvData).AllowDrop = true;
					}
					DictionaryControl.CanDragDrop = true;
					DictionaryControl.SimpleDragDrop = true;
					DictionaryControl.CanDragDropDataSource = false;
					DictionaryControl.AddParentheses = false;
					DictionaryControl.CanBuildTotals = (codeEditorMode & StiCodeEditorMode.Expression) > (StiCodeEditorMode)0;
					DictionaryControl.Build(report);
					DesignerSaveNodes();
					NodesMemoryForEditor.LoadExpNodes((TreeView)(object)DictionaryControl.tvData, restoreSelectedNode: true);
					((Control)DictionaryControl.tvData).DoubleClick += Dictionary_DoubleClick;
					((Control)DictionaryControl.tvData).KeyDown += new KeyEventHandler(Dictionary_KeyDown);
				}
				catch
				{
				}
			}
			if ((codeEditorMode & StiCodeEditorMode.StatusBar) == 0)
			{
				sbEditorInfo.Visible = false;
			}
			Editor.AutoCorrection = false;
			ShowLineNumbersInEditor = ShowLineNumbersInEditor;
			if (((codeEditorMode & StiCodeEditorMode.ReportCode) <= (StiCodeEditorMode)0 && (codeEditorMode & StiCodeEditorMode.Expression) > (StiCodeEditorMode)0) || (codeEditorMode & StiCodeEditorMode.EditorCode) > (StiCodeEditorMode)0)
			{
				BuildAtoms();
			}
			StiGuiHelper.ApplyStyle((Control)(object)contextMenuBar1);
			if (report != null && report.Designer != null && (codeEditorMode & StiCodeEditorMode.ReportCode) > (StiCodeEditorMode)0)
			{
				((Control)this).BackColor = StiGuiHelper.GetControlColor();
			}
		}
		catch
		{
		}
	}

