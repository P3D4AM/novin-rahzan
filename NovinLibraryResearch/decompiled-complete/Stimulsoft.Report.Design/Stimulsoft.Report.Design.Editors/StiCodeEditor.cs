	private void SaveScript(bool alwaysPackScript)
	{
		if (Designer != null && Designer.Report != null && Editor.Modified && (codeEditorMode & StiCodeEditorMode.ReportCode) > (StiCodeEditorMode)0)
		{
			Designer.Report.Script = ((Control)this).Text;
			if (ShowAutoGeneratedCode || alwaysPackScript)
			{
				Designer.Report.ScriptPack();
			}
			Designer.Report.IsModified = true;
			Editor.Modified = false;
		}
	}

	private void OpenScript()
	{
		if (Designer != null && Designer.Report != null)
		{
			string script = Designer.Report.Script;
			if (ShowAutoGeneratedCode || ForceShowAutoGeneratedCode)
			{
				Designer.Report.ScriptUnpack();
			}
			ForceShowAutoGeneratedCode = false;
			((Control)this).Text = Designer.Report.Script;
			Designer.Report.Script = script;
		}
	}

	internal void SaveSettings()
	{
		if (ranges == null)
		{
			ranges = new ArrayList();
		}
		else
		{
			ranges.Clear();
		}
		Editor.Outlining.GetOutlineRanges(ranges);
		position = Editor.Position;
		windowPosition = new Point(Editor.Scrolling.WindowOriginX, Editor.Scrolling.WindowOriginY);
	}

	internal void LoadSettings()
	{
		if (ranges != null)
		{
			((TextSource)Editor.Source).FormatText();
			Editor.Outlining.AllowOutlining = false;
			Editor.Outlining.AllowOutlining = true;
			Editor.Outlining.BeginUpdate();
			try
			{
				foreach (IOutlineRange range in ranges)
				{
					IOutlineRange outlineRange2 = Editor.Outlining.GetOutlineRange(range.StartPoint);
					if (outlineRange2 != null)
					{
						outlineRange2.Visible = range.Visible;
					}
				}
			}
			finally
			{
				Editor.Outlining.EndUpdate();
			}
		}
		Editor.Position = position;
		Editor.Scrolling.WindowOriginX = windowPosition.X;
		Editor.Scrolling.WindowOriginY = windowPosition.Y;
	}

	private bool CheckAddSeparators()
	{
		if (((Control)this).Text.Trim().Length == 0)
		{
			return true;
		}
		int selectionStart = Editor.Selection.SelectionStart;
		if (selectionStart == -1 || ((Control)this).Text.Length < selectionStart)
		{
			return ((Control)this).Text.IndexOf("{", StringComparison.InvariantCulture) == -1;
		}
		for (int num = selectionStart - 1; num >= 0; num--)
		{
			if (((Control)this).Text[num] == '}')
			{
				return true;
			}
			if (((Control)this).Text[num] == '{')
			{
				return false;
			}
		}
		return true;
	}

