		if (File.Exists(StiPath.GetPath(StiDesigner.GetDefaultDesignerConfigPath())))
		{
			try
			{
				FileStream fileStream = new FileStream(StiPath.GetPath(StiDesigner.GetDefaultDesignerConfigPath()), FileMode.Open);
				StiSerializing stiSerializing = new StiSerializing(new StiReportObjectStringConverter());
				stiSerializing.Deserialize(this, fileStream, "StiDesignerConfig");
