			stiDesignerInfo.DrawEventMarkers = StiSettings.GetBool("StiDesigner", "DrawEventMarkers", stiDesignerInfo.DrawEventMarkers);
			double @double = StiSettings.GetDouble("StiDesigner", "Zoom", stiDesignerInfo.Zoom);
			stiDesignerInfo.ViewMode = (StiViewMode)StiSettings.Get("StiDesigner", "ViewMode", stiDesignerInfo.ViewMode);
			stiDesignerInfo.EnableAutoSaveMode = StiSettings.GetBool("StiDesigner", "EnableAutoSaveMode", stiDesignerInfo.EnableAutoSaveMode);
			stiDesignerInfo.AutoSaveInterval = StiSettings.GetInt("StiDesigner", "AutoSaveInterval", stiDesignerInfo.AutoSaveInterval);
