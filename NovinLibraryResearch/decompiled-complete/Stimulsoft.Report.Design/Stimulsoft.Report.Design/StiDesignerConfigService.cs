				StiSettings.Set("StiDesigner", "DrawMarkersWhenMoving", stiDesignerInfo.DrawMarkersWhenMoving);
				StiSettings.Set("StiDesigner", "MarkersStyle", stiDesignerInfo.MarkersStyle);
				StiSettings.Set("StiDesigner", "GridMode", stiDesignerInfo.GridMode);
