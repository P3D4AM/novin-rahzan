	}

	public void LoadLayout()
	{
		string path = StiPath.GetPath(StiDesigner.GetDefaultDockingPanelsConfigPath());
		if (!File.Exists(path))
		{
			return;
		}
		if (!Designer.IsRibbonGuiMode)
		{
			bool visible = Designer.MainMenu.Visible;
			Designer.DotNetBarManager.LoadLayout(path);
			Designer.MainMenu.Visible = visible;
			RemoveOldMessagesPanel();
		}
		if (!Designer.ShowPanelDictionary)
		{
			Designer.ShowPanelDictionary = false;
		}
		if (!Designer.ShowPanelReportTree)
		{
			Designer.ShowPanelReportTree = false;
		}
		if (!Designer.ShowPanelProperties)
		{
			Designer.ShowPanelProperties = false;
		}
		if (!Designer.IsRibbonGuiMode)
		{
			if (!Designer.ShowToolbarBorders)
			{
				Designer.ShowToolbarBorders = false;
			}
			if (Designer.ShowToolbarDockStyle)
			{
				Designer.ShowToolbarDockStyle = true;
			}
			if (!Designer.ShowToolbarFormatting)
			{
				Designer.ShowToolbarLayout = false;
			}
			if (!Designer.ShowToolbarLayout)
			{
				Designer.ShowToolbarLayout = false;
			}
			if (!Designer.ShowToolbarStandard)
			{
				Designer.ShowToolbarStandard = false;
			}
			if (!Designer.ShowToolbarStatusBar)
			{
				Designer.ShowToolbarStatusBar = false;
			}
			if (!Designer.ShowToolbarStyle)
			{
				Designer.ShowToolbarStyle = false;
			}
			if (Designer.ShowToolbarTextFormat)
			{
				Designer.ShowToolbarTextFormat = true;
			}
			if (Designer.ShowToolbarTools)
			{
				Designer.ShowToolbarTools = true;
			}
		}
	}

	private void RemoveOldMessagesPanel()
	{
		try
		{
			foreach (Bar bar in Designer.DotNetBarManager.Bars)
			{
				if (((Control)bar).Text != StiLocalization.Get("Panels", "Messages") && !string.IsNullOrEmpty(((Control)bar).Text))
				{
					continue;
				}
				Designer.DotNetBarManager.Bars.Remove(bar);
				{
					foreach (DockContainerItem item in bar.Items)
					{
						if (item.Text == StiLocalization.Get("Panels", "Messages"))
						{
							bar.Items.Remove(item);
							break;
						}
					}
					break;
				}
			}
		}
		catch
		{
		}
	}

