	public void InitializeRecentFiles()
	{
		Designer.RecentFiles.Clear();
		StiSettings.Load();
		for (int i = 0; i < 15; i++)
		{
			string str = StiSettings.GetStr("StiDesigner", "RecentFile" + i, null);
			if (!string.IsNullOrEmpty(str))
			{
				string[] array = str.Split(new char[1] { '\\' });
				if (array.Length == 3 && array[0].Equals("cloud"))
				{
					Designer.RecentFiles.Add(new StiRecentFile(str, array[2], array[1]));
				}
				else if (!StiOptions.Designer.MainMenu.ShowOnlyExistingRecentFiles || File.Exists(str))
				{
					Designer.RecentFiles.Add(new StiRecentFile(str, Path.GetFileNameWithoutExtension(str), null));
				}
			}
		}
	}

